/**
 * Instala las puertas de calidad de forma idempotente.
 */
export function installInitialGates(existing: QualityGate[]): QualityGate[] {
  const existingIds = new Set(existing.map(g => g.id));
  const toAdd = INITIAL_GATES.filter(g => !existingIds.has(g.id));
  return [...existing, ...toAdd];
}
